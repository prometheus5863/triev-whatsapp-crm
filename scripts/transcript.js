// Runs one conversation through the real handler in DRY_RUN and writes
// docs/transcript.html (a chat-style view used for the README screenshot).
process.env.DRY_RUN = '1';
const fs = require('fs');
const path = require('path');
const webhook = require('../src/controllers/webhook');
const { outbox } = require('../src/services/gupshup');

const rider = ['help', 'EV-CHASSIS-12345', '1', 'Range dropping quickly', 'Varanasi', 'Lanka Gate, near BHU'];
const esc = (s) => s.replace(/[&<>]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;' }[c]));
const fmt = (s) => esc(s).replace(/\*(.+?)\*/g, '<b>$1</b>').replace(/\n/g, '<br>');

(async () => {
    const rows = [];
    for (const text of rider) {
        const before = outbox.length;
        rows.push(`<div class="m me">${fmt(text)}</div>`);
        await webhook.process('919800000000', text);
        for (const o of outbox.slice(before)) rows.push(`<div class="m bot">${fmt(o.text)}</div>`);
    }
    const html = `<!doctype html><meta charset="utf-8"><title>TriEV RSA bot transcript (dry run)</title>
<style>body{margin:0;background:#0b141a;font:15px/1.4 system-ui,sans-serif;color:#e9edef}
.h{background:#202c33;padding:14px 18px;font-weight:600}.h small{display:block;font-weight:400;color:#8696a0}
.c{max-width:520px;margin:0 auto;padding:16px;display:flex;flex-direction:column;gap:8px}
.m{padding:8px 12px;border-radius:10px;max-width:80%;white-space:normal}
.me{align-self:flex-end;background:#005c4b}.bot{align-self:flex-start;background:#202c33}</style>
<div class="h">TriEV RSA Support<small>dry-run transcript, generated by scripts/transcript.js</small></div>
<div class="c">${rows.join('\n')}</div>`;
    fs.writeFileSync(path.join(__dirname, '..', 'docs', 'transcript.html'), html);
    console.log('wrote docs/transcript.html');
})();
